CREATE TABLE CALCULADORA_OPERACIONES
(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO1 NUMBER(20,10) NOT NULL,
    OPERADOR VARCHAR2(5) NOT NULL,
    NUMERO2 NUMBER(20,10) NOT NULL,
    RESULTADO NUMBER(30,10) NOT NULL,
    FECHA_OPERACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_CALCULADORA_OPERACIONES
        PRIMARY KEY (ID)
);

COMMIT;


-- veirificar la tabla.
SELECT
    ID,
    NUMERO1,
    OPERADOR,
    NUMERO2,
    RESULTADO,
    FECHA_OPERACION
FROM CALCULADORA_OPERACIONES
ORDER BY ID DESC;

